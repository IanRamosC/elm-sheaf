import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { basename, join } from "node:path";
import { elmString } from "../src/elm/generate";
import { elmValueName } from "../src/elm/names";

const FIXTURES = join(import.meta.dir, "../../tests/fixtures/protocol");
const MODULE_FILE = join(import.meta.dir, "../../tests/ProtocolFixtures.elm");

type Fixture = { name: string; json: string };

function readFixtures(): Fixture[] {
  return readdirSync(FIXTURES)
    .filter((file) => file.endsWith(".json"))
    .sort()
    .map((file) => {
      const name = elmValueName(basename(file, ".json"));
      if (!name.ok) {
        throw new Error(`${file}: ${name.error}`);
      }
      return {
        name: name.value,
        json: readFileSync(join(FIXTURES, file), "utf8"),
      };
    });
}

/**
 * `elm-test-rs` cannot read files, so the Elm side gets the shared fixtures
 * as one `String` value each.
 */
export function embeddedFixtureModule(): string {
  const fixtures = readFixtures();
  const exposed = fixtures.map(({ name }) => name).join(", ");
  const values = fixtures.map(
    ({ name, json }) => `${name} : String\n${name} =\n    ${elmString(json)}\n`,
  );
  return [
    "-- Generated by cli/scripts/embed-protocol-fixtures.ts. Do not edit.",
    "",
    "",
    `module ProtocolFixtures exposing (${exposed})`,
    "",
    "",
    ...values.flatMap((value) => [value, ""]),
  ]
    .join("\n")
    .trimEnd()
    .concat("\n");
}

if (import.meta.main) {
  writeFileSync(MODULE_FILE, embeddedFixtureModule());
}
