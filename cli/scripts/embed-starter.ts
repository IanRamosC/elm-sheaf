import { readFileSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";

const REPOSITORY = join(import.meta.dir, "../..");
const STARTER_FOLDER = "cli/templates/default";
const MODULE_FILE = join(import.meta.dir, "../src/init/starter.generated.ts");

/**
 * The starter's files as `/`-separated paths relative to the starter, sorted.
 * Tracked and new files count; ignored ones (`.DS_Store`, build output) never do.
 */
function starterPaths(): string[] {
  const listing = Bun.spawnSync(
    [
      "git",
      "ls-files",
      "-z",
      "--cached",
      "--others",
      "--exclude-standard",
      STARTER_FOLDER,
    ],
    { cwd: REPOSITORY },
  );
  if (!listing.success) {
    throw new Error(`git ls-files failed: ${listing.stderr.toString()}`);
  }
  return listing.stdout
    .toString()
    .split("\0")
    .filter((path) => path !== "")
    .map((path) => path.slice(STARTER_FOLDER.length + 1))
    .sort();
}

/** Decodes a starter file. Throws, naming the file, when it is not UTF-8 text. */
export function decodeStarterFile(path: string, bytes: Uint8Array): string {
  try {
    return new TextDecoder("utf-8", { fatal: true }).decode(bytes);
  } catch {
    throw new Error(
      `${STARTER_FOLDER}/${path} is not UTF-8 text. Every starter file must be text.`,
    );
  }
}

export function readStarter(): Map<string, string> {
  return new Map(
    starterPaths().map((path) => [
      path,
      decodeStarterFile(
        path,
        readFileSync(join(REPOSITORY, STARTER_FOLDER, ...path.split("/"))),
      ),
    ]),
  );
}

export function embeddedStarterModule(): string {
  const entries = [...readStarter()].map(
    ([path, text]) => `  [${JSON.stringify(path)}, ${JSON.stringify(text)}],`,
  );
  return [
    "// Generated by `bun run embed-starter` from cli/templates/default/. Do not edit.",
    "",
    "export const STARTER: ReadonlyMap<string, string> = new Map([",
    ...entries,
    "]);",
    "",
  ].join("\n");
}

if (import.meta.main) {
  writeFileSync(MODULE_FILE, embeddedStarterModule());
  const format = Bun.spawnSync(
    [
      "bunx",
      "--bun",
      "biome",
      "format",
      "--write",
      relative(process.cwd(), MODULE_FILE),
    ],
    { stderr: "inherit" },
  );
  if (!format.success) process.exit(1);
}
