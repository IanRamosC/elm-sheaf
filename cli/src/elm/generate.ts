import type { SourceDocument } from "../content/document";
import { elmModuleName } from "./names";

const GENERATED_MARKER = "-- Generated by Sheaf. Do not edit.";

type Reference = { name: string; document: SourceDocument };

function byCodePoint(a: string, b: string): number {
  return a < b ? -1 : a > b ? 1 : 0;
}

/** Elm has fewer string escapes than JSON, so control characters use `\u{XXXX}`. */
export function elmString(text: string): string {
  const escaped = text.replace(/[\\"\p{Cc}]/gu, (character) => {
    switch (character) {
      case "\\":
      case '"':
        return `\\${character}`;
      case "\n":
        return "\\n";
      case "\r":
        return "\\r";
      case "\t":
        return "\\t";
      default:
        return `\\u{${character.charCodeAt(0).toString(16).padStart(4, "0")}}`;
    }
  });
  return `"${escaped}"`;
}

/** Paths are user-controlled; Elm comments nest, so `{-` and `-}` must not survive. */
function inDocComment(text: string): string {
  return text
    .replace(/\s*[\r\n]+\s*/g, " ")
    .replaceAll("{-", "{ -")
    .replaceAll("-}", "- }");
}

function referenceDefinition({ name, document }: Reference): string {
  return [
    `{-| \`${inDocComment(document.sourcePath)}\``,
    "-}",
    `${name} : Sheaf.Ref.Ref`,
    `${name} =`,
    `    Sheaf.Ref.fromId ${elmString(document.id)}`,
  ].join("\n");
}

function allReferences(references: Reference[]): string {
  const [first, ...rest] = references;
  const list =
    first === undefined
      ? "    []"
      : [
          `    [ ${first.name}`,
          ...rest.map(({ name }) => `    , ${name}`),
          "    ]",
        ].join("\n");
  return [
    "{-| Every reference in the collection, for templates that list them all.",
    "-}",
    "all : List Sheaf.Ref.Ref",
    "all =",
    list,
  ].join("\n");
}

function collectionModule(
  collection: string,
  moduleName: string,
  references: Reference[],
): string {
  // elm-format keeps the exposing list sorted, so it is written that way.
  const exposed = ["all", ...references.map(({ name }) => name)]
    .sort(byCodePoint)
    .join(", ");
  return [
    GENERATED_MARKER,
    "",
    "",
    `module Content.${moduleName} exposing (${exposed})`,
    "",
    `{-| References to the documents in \`content/${inDocComment(collection)}/\`.`,
    "-}",
    "",
    "import Sheaf.Ref",
    "",
    "",
    allReferences(references),
    ...references.flatMap((reference) => [
      "",
      "",
      referenceDefinition(reference),
    ]),
    "",
  ].join("\n");
}

const WORKER_ENTRY_POINT = `${GENERATED_MARKER}


port module SheafMain exposing (main)

{-| The program the host compiles and runs: it connects the site to the
host's ports.
-}

import Json.Decode
import Json.Encode
import Sheaf.Program
import Site


port sheafRequest : (Json.Decode.Value -> msg) -> Sub msg


port sheafResponse : Json.Encode.Value -> Cmd msg


main =
    Sheaf.Program.worker
        { request = sheafRequest
        , respond = sheafResponse
        }
        Site.main
`;

/**
 * The Elm source the host writes to `.sheaf/gen/` before compiling, keyed by
 * path relative to that folder. `collections` lists every collection, so an
 * empty one still gets a module that templates can import.
 *
 * Collection names must already have passed `elmModuleName`, and every
 * document needs an entry in `names`; both are checked earlier in the build.
 */
export function generateElm(
  collections: string[],
  documents: SourceDocument[],
  names: Map<string, string>,
): Map<string, string> {
  const files = new Map<string, string>();

  for (const collection of collections) {
    const moduleName = elmModuleName(collection);
    if (!moduleName.ok) {
      throw new Error(moduleName.error);
    }
    const references = documents
      .filter((document) => document.collection === collection)
      .map((document) => ({ name: names.get(document.id) ?? "", document }))
      .sort((a, b) => byCodePoint(a.name, b.name));
    files.set(
      `Content/${moduleName.value}.elm`,
      collectionModule(collection, moduleName.value, references),
    );
  }

  files.set("SheafMain.elm", WORKER_ENTRY_POINT);
  return files;
}
