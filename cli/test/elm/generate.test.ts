import { describe, expect, test } from "bun:test";
import { spawnSync } from "node:child_process";
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import type { SourceDocument } from "../../src/content/document";
import { generateElm } from "../../src/elm/generate";
import { assignValueNames } from "../../src/elm/names";

function documentAt(collection: string, slug: string): SourceDocument {
  return {
    id: `${collection}/${slug}`,
    collection,
    sourcePath: `content/${collection}/${slug}.md`,
    slug,
    draft: false,
    excluded: false,
    frontmatter: {},
    frontmatterPositions: [],
    aliases: [],
    body: "",
    bodyStartLine: 1,
  };
}

function generate(collections: string[], documents: SourceDocument[]) {
  const names = assignValueNames(documents);
  if (!names.ok) {
    throw new Error("test documents must have valid names");
  }
  return generateElm(collections, documents, names.value);
}

function elmFormatExitCode(files: Map<string, string>): number {
  const directory = mkdtempSync(join(tmpdir(), "sheaf-gen-"));
  try {
    for (const [path, content] of files) {
      const target = join(directory, path);
      mkdirSync(dirname(target), { recursive: true });
      writeFileSync(target, content);
    }
    return (
      spawnSync("elm-format", ["--validate", directory], { encoding: "utf8" })
        .status ?? -1
    );
  } finally {
    rmSync(directory, { recursive: true, force: true });
  }
}

const documents = [
  documentAt("posts", "hello-world"),
  documentAt("posts", "2026-recap"),
  documentAt("pages", "about"),
];

describe("generateElm", () => {
  const files = generate(["posts", "pages"], documents);

  test("writes one module per collection plus the entry point", () => {
    expect([...files.keys()].sort()).toEqual([
      "Content/Pages.elm",
      "Content/Posts.elm",
      "SheafMain.elm",
    ]);
  });

  test("collection module", () => {
    expect(files.get("Content/Posts.elm")).toMatchSnapshot();
  });

  test("entry point", () => {
    expect(files.get("SheafMain.elm")).toMatchSnapshot();
  });

  test("every file is marked as generated", () => {
    for (const content of files.values()) {
      expect(
        content.startsWith(
          "-- Generated by Sheaf; do not edit. You may use this file under the 0BSD licence.\n\n\n",
        ),
      ).toBe(true);
    }
  });

  test("all files are valid elm-format output", () => {
    expect(elmFormatExitCode(files)).toBe(0);
  });

  test("a collection without documents still gets a valid module", () => {
    const withEmpty = generate(["posts", "drafts"], [documentAt("posts", "a")]);
    expect(withEmpty.get("Content/Drafts.elm")).toContain("all =\n    []");
    expect(elmFormatExitCode(withEmpty)).toBe(0);
  });

  test("a document slugged all does not clash with the all list", () => {
    const files = generate(["posts"], [documentAt("posts", "all")]);
    const module = files.get("Content/Posts.elm");
    expect(module).toContain("exposing (all, all_)");
    expect(module).toContain('all_ =\n    Sheaf.Ref.fromId "posts/all"');
    expect(elmFormatExitCode(files)).toBe(0);
  });

  test("escapes quotes, tabs and non-ASCII text in reference ids", () => {
    const document = { ...documentAt("posts", "x"), id: 'posts/"é"\tend' };
    const files = generateElm(
      ["posts"],
      [document],
      new Map([[document.id, "x"]]),
    );
    expect(files.get("Content/Posts.elm")).toContain(
      'Sheaf.Ref.fromId "posts/\\"é\\"\\tend"',
    );
    expect(elmFormatExitCode(files)).toBe(0);
  });

  test("keeps comment delimiters in file names out of doc comments", () => {
    const files = generate(["posts"], [documentAt("posts", "a-}b")]);
    expect(elmFormatExitCode(files)).toBe(0);
    expect(files.get("Content/Posts.elm")).toContain("content/posts/a- }b.md");
  });

  test("keeps comment delimiters in collection names out of the module doc", () => {
    const files = generate(["a{-b"], []);
    expect(elmFormatExitCode(files)).toBe(0);
  });
});
